DROP TABLE IF EXISTS PRICES;

CREATE TABLE PRICES (
    ID         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BRAND_ID   BIGINT        NOT NULL,
    START_DATE TIMESTAMP     NOT NULL,
    END_DATE   TIMESTAMP     NOT NULL,
    PRICE_LIST BIGINT        NOT NULL,
    PRODUCT_ID BIGINT        NOT NULL,
    PRIORITY   INT           NOT NULL,
    PRICE      DECIMAL(12, 4) NOT NULL,
    CURR       VARCHAR(3)    NOT NULL,
    CONSTRAINT CHK_PRICES_BRAND      CHECK (BRAND_ID > 0),
    CONSTRAINT CHK_PRICES_PRODUCT    CHECK (PRODUCT_ID > 0),
    CONSTRAINT CHK_PRICES_PRICE_LIST CHECK (PRICE_LIST > 0),
    CONSTRAINT CHK_PRICES_PERIOD     CHECK (END_DATE >= START_DATE),
    CONSTRAINT CHK_PRICES_PRIORITY   CHECK (PRIORITY >= 0),
    CONSTRAINT CHK_PRICES_PRICE      CHECK (PRICE >= 0)
);

CREATE INDEX IDX_PRICES_LOOKUP ON PRICES (BRAND_ID, PRODUCT_ID, START_DATE, END_DATE);
